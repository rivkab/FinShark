// The AppleScript of FinShark.app (DESIGN D20, "A FinShark app"). Pure, so it is tested.
//
// macOS grants folder access (iCloud Drive, Documents, external drives) per app, and a
// process counts as part of the app that started it. Started from this applet, FinShark
// asks for and gets access as "FinShark", not as Terminal or Claude Code, so neither of
// those needs access to iCloud Drive.
//
// The applet stays open while FinShark runs: it starts the server in the background, checks
// every few seconds that it is still running, and stops it when the app is quit.

export interface LauncherConfig {
  repoRoot: string;
  /** Directory holding the Node 24 `node` and `npm` binaries. */
  nodeBinDir: string;
  vaultRoot: string;
  logFile: string;
}

/** An AppleScript string literal. */
export function asString(s: string): string {
  return `"${s.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

export function appleScriptSource(c: LauncherConfig): string {
  return `-- FinShark.app: generated by \`npm run make-app\`. Edit server/src/launcher/applescript.ts instead.
property repoRoot : ${asString(c.repoRoot)}
property nodeBinDir : ${asString(c.nodeBinDir)}
property vaultRoot : ${asString(c.vaultRoot)}
property logFile : ${asString(c.logFile)}
property serverPid : ""
property quitting : false

on run
  -- Only the subshell goes to the background (";" before it, not "&&"), with its input and
  -- output away from this applet; otherwise "do shell script" waits for it and the applet
  -- never gets to idle or quit. The web app is built first; then the subshell becomes the
  -- server (exec), so $! is the server's pid.
  set cmd to "cd " & quoted form of repoRoot & " || exit 1" & ¬
    "; export PATH=" & quoted form of nodeBinDir & ":/usr/bin:/bin:/usr/sbin:/sbin" & ¬
    "; export FINSHARK_VAULT=" & quoted form of vaultRoot & ¬
    "; (npm run build -w web -- --logLevel warn && exec node server/src/main.ts) < /dev/null > " & quoted form of logFile & " 2>&1 & echo $!"
  set serverPid to do shell script cmd
end run

on idle
  try
    do shell script "kill -0 " & serverPid
  on error
    if not quitting then
      display alert "FinShark has stopped" message "Details are in " & logFile & "." as warning
      set quitting to true
      quit
    end if
  end try
  return 5
end idle

-- Opening the app again while it runs opens FinShark in the browser again.
on reopen
  try
    set link to do shell script "grep -o 'http://127.0.0.1:[0-9]*/auth?token=[A-Za-z0-9_-]*' " & quoted form of logFile & " | tail -1"
    if link is not "" then do shell script "open " & quoted form of link
  end try
end reopen

on quit
  set quitting to true
  if serverPid is not "" then
    try
      do shell script "kill " & serverPid
      -- Give a running backup time to finish (the server waits for it before exiting).
      repeat 120 times
        do shell script "kill -0 " & serverPid
        delay 0.5
      end repeat
    end try
  end if
  continue quit
end quit
`;
}
